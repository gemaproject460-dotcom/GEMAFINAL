// =====================================================
//                 IDIOMA ACTUAL
// =====================================================

let idiomaActual = localStorage.getItem("idiomaGemaKids") || "es";


// =====================================================
//                 CAMBIAR IDIOMA
// =====================================================

function cambiarIdioma(idioma) {

    // Verificar que el idioma exista
    if (!textos[idioma]) {
        return;
    }

    idiomaActual = idioma;

    // Buscar todos los elementos con data-i18n
    const elementos = document.querySelectorAll("[data-i18n]");

    elementos.forEach(elemento => {

        const clave = elemento.getAttribute("data-i18n");

        // Si existe la traducción
        if (textos[idioma][clave]) {

            elemento.textContent = textos[idioma][clave];

        }

    });

    // Guardar idioma
    localStorage.setItem("idiomaGemaKids", idioma);

    // Actualizar botón
    actualizarBotonIdioma();
}


// =====================================================
//             BOTÓN DEL IDIOMA
// =====================================================

function actualizarBotonIdioma() {

    const boton = document.getElementById("idiomaBtn");

    if (!boton) {
        return;
    }

    if (idiomaActual === "es") {
        boton.setAttribute("title", "Cambiar a inglés");
        boton.setAttribute("aria-label", "Cambiar a inglés");
    } else {
        boton.setAttribute("title", "Switch to Spanish");
        boton.setAttribute("aria-label", "Switch to Spanish");
    }

}


// =====================================================
//             EVENTO DEL BOTÓN
// =====================================================

document.addEventListener("DOMContentLoaded", function () {

    const botonIdioma = document.getElementById("idiomaBtn");

    if (botonIdioma) {

        botonIdioma.addEventListener("click", function () {

            if (idiomaActual === "es") {

                cambiarIdioma("en");

            } else {

                cambiarIdioma("es");

            }

        });

    }

    // Aplicar idioma guardado al cargar
    cambiarIdioma(idiomaActual);

});



// =====================================================
//                 MÚSICA DE GEMA KIDS
// =====================================================

const musica = document.getElementById("musicaFondo");
const musicaBtn = document.getElementById("musicaBtn");

let musicaActiva = false;


// =====================================================
//                 BOTÓN DE MÚSICA
// =====================================================

if (musicaBtn) {

    musicaBtn.addEventListener("click", function () {

        if (!musicaActiva) {

            musica.volume = 0.25;

            musica.play();

            musicaActiva = true;

            musicaBtn.innerHTML =
                '<i class="fa-solid fa-volume-high"></i>';

        } else {

            musica.pause();

            musicaActiva = false;

            musicaBtn.innerHTML =
                '<i class="fa-solid fa-volume-xmark"></i>';
        }

    });

}

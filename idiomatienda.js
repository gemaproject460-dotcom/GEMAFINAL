// ==========================================
// APLICAR IDIOMA
// ==========================================

function aplicarIdiomaTienda(idioma) {

    if (!traduccionesTienda[idioma]) {
        idioma = "es";
    }

    localStorage.setItem("idioma", idioma);

    // Traducir todos los elementos data-i18n

    document.querySelectorAll("[data-i18n]").forEach(elemento => {

        const clave = elemento.getAttribute("data-i18n");

        const texto =
            traduccionesTienda[idioma][clave];

        if (texto !== undefined) {

            elemento.textContent = texto;

        }

    });

    // Traducir título de la página

    const titulo =
        traduccionesTienda[idioma]["tienda.tituloPagina"];

    if (titulo) {
        document.title = titulo;
    }

    // Actualizar productos
    if (typeof actualizarIdiomaProductos === "function") {
        actualizarIdiomaProductos(idioma);
    }
}


// ==========================================
// BOTÓN DE IDIOMA
// ==========================================

function cambiarIdioma(idioma) {

    aplicarIdiomaTienda(idioma);

    // Actualizar tienda si existe la función
    if (typeof actualizarIdiomaTienda === "function") {
        actualizarIdiomaTienda();
    }
}


// ==========================================
// CARGAR IDIOMA AL ABRIR
// ==========================================

document.addEventListener("DOMContentLoaded", () => {

    const idiomaGuardado =
        localStorage.getItem("idioma") || "es";

    aplicarIdiomaTienda(idiomaGuardado);

});
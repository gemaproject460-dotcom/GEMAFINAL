function cambiarIdioma(idioma){

    // Traducción normal (textContent)

    document.querySelectorAll("[data-i18n]").forEach(elemento => {

        const clave = elemento.getAttribute("data-i18n");

        if(textos[idioma] && textos[idioma][clave]){

            elemento.textContent = textos[idioma][clave];

        }

    });

    // Traducción de placeholders

    document.querySelectorAll("[data-i18n-placeholder]").forEach(elemento => {

        const clave = elemento.getAttribute("data-i18n-placeholder");

        if(textos[idioma] && textos[idioma][clave]){

            elemento.placeholder = textos[idioma][clave];

        }

    });

    // Traducción de options

    document.querySelectorAll("option[data-i18n]").forEach(elemento => {

        const clave = elemento.getAttribute("data-i18n");

        if(textos[idioma] && textos[idioma][clave]){

            elemento.textContent = textos[idioma][clave];

        }

    });

    // Guardar idioma

    localStorage.setItem("idioma", idioma);

}

//==================================================
// CARGAR IDIOMA GUARDADO
//==================================================

window.addEventListener("DOMContentLoaded", () => {

    const idiomaGuardado =
        localStorage.getItem("idioma") || "es";

    cambiarIdioma(idiomaGuardado);

});